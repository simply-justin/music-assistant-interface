"""Generates the UI fonts and icon fonts (LVGL C files) from the design spec.

Usage: python3 gen_assets.py <dir with Inter-*.ttf and Phosphor-{Bold,Fill}.ttf + style.css files>
Needs node (npx lv_font_conv@1.5.3). Output goes to ../fonts/. Re-run only when the type scale,
glyph ranges or icon set change; the generated files are committed.

Sources: Inter 4.1 (rsms/inter, OFL), Phosphor Icons 2.1.1 (@phosphor-icons/web, MIT).
"""
import pathlib
import re
import subprocess
import sys

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).resolve().parent.parent / "fonts"
CONV = ["npx", "-y", "lv_font_conv@1.5.3", "--no-compress", "--format", "lvgl", "--lv-include", "lvgl.h"]

# Basic Latin, Latin-1, Latin Extended-A + typographic punctuation (spec §1, Typography).
TEXT_RANGE = "0x20-0x7E,0xA0-0x17F,0x2013,0x2014,0x2018,0x2019,0x201C,0x201D,0x2022,0x2026,0x2212"

# name: (size, weight file, range)
FONTS = {
    "label": (14, "SemiBold", TEXT_RANGE),
    "meta": (16, "Medium", TEXT_RANGE),
    "body": (18, "SemiBold", TEXT_RANGE),
    "lead": (20, "Medium", TEXT_RANGE),
    "h2": (24, "SemiBold", TEXT_RANGE),
    "h1": (36, "Bold", TEXT_RANGE),
    "display": (48, "Bold", TEXT_RANGE),
    "clock": (140, "Light", "0x20,0x30-0x3A"),  # digits, colon, space only
}

# Spec icon name -> Phosphor glyph. "fill:" = Phosphor Fill style.
ICONS = {
    "home": "house", "search": "magnifying-glass", "library": "books", "queue": "queue",
    "settings": "sliders-horizontal", "play": "fill:play", "pause": "fill:pause", "stop": "fill:stop",
    "prev": "fill:skip-back", "next": "fill:skip-forward", "shuffle": "shuffle", "repeat": "repeat",
    "repeat_one": "repeat-once", "heart": "heart", "heart_filled": "fill:heart", "plus": "plus",
    "minus": "minus", "more": "dots-three", "close": "x", "chevron_down": "caret-down",
    "chevron_up": "caret-up", "chevron_left": "caret-left", "chevron_right": "caret-right",
    "speaker": "speaker-hifi", "volume": "speaker-high", "mute": "speaker-x", "check": "check",
    "warning": "warning", "info": "info", "wifi": "wifi-high", "server": "hard-drives", "radio": "radio",
    "trash": "trash", "undo": "arrow-counter-clockwise", "add_to_queue": "list-plus",
    "play_next": "fill:skip-forward", "lock": "lock", "eye": "eye", "refresh": "arrows-clockwise",
    "moon": "moon", "sun": "sun", "phone": "device-mobile", "chart": "chart-bar", "power": "power",
    "edit": "pencil-simple", "playlist_add": "list-plus", "artist": "user", "album": "vinyl-record", "language": "globe",
}
ICON_SIZES = [22, 28, 32, 48]
FILL_BASE = 0xF8E0  # Fill glyphs are remapped here so they don't clash with Bold codepoints


def run(args):
    subprocess.run(CONV + args, check=True, stdout=subprocess.DEVNULL)


def codes(style):
    css = (SRC / f"{style}.css").read_text()
    return {n: int(c, 16) for n, c in re.findall(r"\.ph-[a-z]+\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css)}


def main():
    OUT.mkdir(exist_ok=True)
    header_only = "--header-only" in sys.argv
    for name, (size, weight, rng) in FONTS.items():
        if header_only:
            break
        run(["--font", str(SRC / f"Inter-{weight}.ttf"), "-r", rng, "--size", str(size), "--bpp", "4",
             "--lv-font-name", f"ui_font_{name}", "-o", str(OUT / f"ui_font_{name}.c")])

    bold, fill = codes("bold"), codes("fill")
    bold_ranges, fill_ranges, cps = [], [], {}
    fill_slots = {}
    for spec_name, glyph in ICONS.items():
        if glyph.startswith("fill:"):
            g = glyph[5:]
            if g not in fill_slots:
                fill_slots[g] = FILL_BASE + len(fill_slots)
                fill_ranges.append(f"0x{fill[g]:X}=>0x{fill_slots[g]:X}")
            cps[spec_name] = fill_slots[g]
        else:
            if bold[glyph] not in cps.values():
                bold_ranges.append(f"0x{bold[glyph]:X}")
            cps[spec_name] = bold[glyph]
    for size in ([] if header_only else ICON_SIZES):
        run(["--font", str(SRC / "Phosphor-Bold.ttf"), "-r", ",".join(bold_ranges),
             "--font", str(SRC / "Phosphor-Fill.ttf"), "-r", ",".join(fill_ranges),
             "--size", str(size), "--bpp", "4", "--lv-font-name", f"ui_icons_{size}", "-o", str(OUT / f"ui_icons_{size}.c")])

    hdr = ["// Generated by tools/gen_assets.py. Do not edit.", "#pragma once", "#include \"lvgl.h\"", "",
           "extern \"C\" {  // the fonts are C globals"]
    hdr += [f"LV_FONT_DECLARE(ui_font_{n})" for n in FONTS]
    hdr += [f"LV_FONT_DECLARE(ui_icons_{s})" for s in ICON_SIZES]
    hdr += ["}", "", "namespace ui {", "", "// Icon glyphs as UTF-8 strings: lv_label_set_text(label, icon::play).", "namespace icon {"]
    for n, cp in cps.items():
        utf8 = chr(cp).encode("utf-8")
        hdr.append(f"inline constexpr const char* {n} = \"{''.join(f'\\x{b:02X}' for b in utf8)}\";")
    hdr += ["}  // namespace icon", "", "}  // namespace ui", ""]
    (OUT / "assets.hpp").write_text("\n".join(hdr))


if __name__ == "__main__":
    main()
